// Command schemasnap writes the schema snapshot the SDK's documents are
// checked against (platform/testdata/schema.graphql).
//
// It reads an introspection result of the platform API and keeps only what
// the SDK uses: the root fields its documents name, the types reachable
// from them, and of those types the fields the documents select. Deprecated
// members and descriptions are left out.
//
//	go run ./internal/schemasnap -in introspection.json
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/theorigamicorporation/rsodev-go/internal/guard"
)

type typeRef struct {
	Kind   string   `json:"kind"`
	Name   string   `json:"name"`
	OfType *typeRef `json:"ofType"`
}

func (t *typeRef) String() string {
	switch t.Kind {
	case "NON_NULL":
		return t.OfType.String() + "!"
	case "LIST":
		return "[" + t.OfType.String() + "]"
	}
	return t.Name
}

func (t *typeRef) named() string {
	for t.OfType != nil {
		t = t.OfType
	}
	return t.Name
}

type member struct {
	Name         string   `json:"name"`
	Args         []member `json:"args"`
	Type         typeRef  `json:"type"`
	IsDeprecated bool     `json:"isDeprecated"`
	DefaultValue *string  `json:"defaultValue"`
}

type fullType struct {
	Kind        string   `json:"kind"`
	Name        string   `json:"name"`
	Fields      []member `json:"fields"`
	InputFields []member `json:"inputFields"`
	EnumValues  []member `json:"enumValues"`
	// PossibleTypes are the members of a union.
	PossibleTypes []typeRef `json:"possibleTypes"`
}

type schema struct {
	QueryType        *struct{ Name string } `json:"queryType"`
	MutationType     *struct{ Name string } `json:"mutationType"`
	SubscriptionType *struct{ Name string } `json:"subscriptionType"`
	Types            []fullType             `json:"types"`
}

var builtin = map[string]bool{"String": true, "Int": true, "Float": true, "Boolean": true, "ID": true}

func main() {
	in := flag.String("in", "", "introspection result (JSON)")
	out := flag.String("out", filepath.Join("platform", "testdata", "schema.graphql"), "snapshot to write")
	source := flag.String("source", "platform", "directory of the SDK's Go sources")
	flag.Parse()
	if err := run(*in, *out, *source); err != nil {
		fmt.Fprintln(os.Stderr, "schemasnap:", err)
		os.Exit(1)
	}
}

func run(in, out, source string) error {
	raw, err := os.ReadFile(in) //nolint:gosec // a developer tool reading the file it was pointed at
	if err != nil {
		return err
	}
	var envelope struct {
		Schema *schema `json:"__schema"`
		Data   struct {
			Schema *schema `json:"__schema"`
		} `json:"data"`
	}
	if err := json.Unmarshal(raw, &envelope); err != nil {
		return err
	}
	s := envelope.Schema
	if s == nil {
		s = envelope.Data.Schema
	}
	if s == nil {
		return fmt.Errorf("%s holds no introspection result", in)
	}
	used, err := identifiers(source)
	if err != nil {
		return err
	}
	types := map[string]*fullType{}
	for i := range s.Types {
		types[s.Types[i].Name] = &s.Types[i]
	}
	roots := map[string]bool{}
	for _, root := range []*struct{ Name string }{s.QueryType, s.MutationType} {
		if root != nil {
			roots[root.Name] = true
		}
	}

	keep := func(m member) bool {
		if m.IsDeprecated || guard.Refused(m.Name) != "" || guard.Refused(m.Type.named()) != "" {
			return false
		}
		for _, arg := range m.Args {
			if guard.Refused(arg.Name) != "" || guard.Refused(arg.Type.named()) != "" {
				return false
			}
		}
		return true
	}

	kept := map[string]*fullType{}
	var visit func(name string)
	visit = func(name string) {
		t := types[name]
		if t == nil || builtin[name] || kept[name] != nil || strings.HasPrefix(name, "__") {
			return
		}
		pruned := &fullType{Kind: t.Kind, Name: t.Name}
		kept[name] = pruned
		for _, f := range t.Fields {
			if !keep(f) || !used[f.Name] {
				continue
			}
			pruned.Fields = append(pruned.Fields, f)
			visit(f.Type.named())
			for _, arg := range f.Args {
				visit(arg.Type.named())
			}
		}
		for _, f := range t.InputFields {
			if !keep(f) {
				continue
			}
			pruned.InputFields = append(pruned.InputFields, f)
			visit(f.Type.named())
		}
		if t.Kind == "UNION" {
			for _, possible := range t.PossibleTypes {
				if guard.Refused(possible.Name) == "" {
					pruned.PossibleTypes = append(pruned.PossibleTypes, possible)
					visit(possible.Name)
				}
			}
		}
		for _, v := range t.EnumValues {
			if !v.IsDeprecated && guard.Refused(v.Name) == "" {
				pruned.EnumValues = append(pruned.EnumValues, v)
			}
		}
	}
	for root := range roots {
		visit(root)
	}

	names := make([]string, 0, len(kept))
	for name := range kept {
		names = append(names, name)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("# The part of the platform API this SDK uses. Generated by\n# internal/schemasnap; do not edit.\n\n")
	for _, name := range names {
		t := kept[name]
		switch t.Kind {
		case "SCALAR":
			fmt.Fprintf(&b, "scalar %s\n\n", name)
		case "ENUM":
			fmt.Fprintf(&b, "enum %s {\n", name)
			for _, v := range t.EnumValues {
				fmt.Fprintf(&b, "  %s\n", v.Name)
			}
			b.WriteString("}\n\n")
		case "UNION":
			members := make([]string, 0, len(t.PossibleTypes))
			for _, possible := range t.PossibleTypes {
				members = append(members, possible.Name)
			}
			fmt.Fprintf(&b, "union %s = %s\n\n", name, strings.Join(members, " | "))
		case "INPUT_OBJECT":
			fmt.Fprintf(&b, "input %s {\n", name)
			for _, f := range t.InputFields {
				fmt.Fprintf(&b, "  %s: %s\n", f.Name, f.Type.String())
			}
			b.WriteString("}\n\n")
		case "OBJECT":
			if len(t.Fields) == 0 {
				// A type none of whose fields is selected still has to exist.
				fmt.Fprintf(&b, "type %s {\n  _: Boolean\n}\n\n", name)
				continue
			}
			fmt.Fprintf(&b, "type %s {\n", name)
			for _, f := range t.Fields {
				b.WriteString("  " + f.Name)
				if len(f.Args) > 0 {
					args := make([]string, 0, len(f.Args))
					for _, arg := range f.Args {
						args = append(args, arg.Name+": "+arg.Type.String())
					}
					b.WriteString("(" + strings.Join(args, ", ") + ")")
				}
				fmt.Fprintf(&b, ": %s\n", f.Type.String())
			}
			b.WriteString("}\n\n")
		}
	}
	return os.WriteFile(out, []byte(strings.TrimRight(b.String(), "\n")+"\n"), 0o600)
}

var word = regexp.MustCompile(`[A-Za-z_][A-Za-z0-9_]*`)

// identifiers collects every name that appears in a raw string literal of
// the SDK's non-test sources: its GraphQL documents and field lists are
// written as raw strings, everything else is not.
func identifiers(dir string) (map[string]bool, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	used := map[string]bool{}
	fset := token.NewFileSet()
	for _, file := range files {
		if strings.HasSuffix(file, "_test.go") {
			continue
		}
		parsed, err := parser.ParseFile(fset, file, nil, 0)
		if err != nil {
			return nil, err
		}
		ast.Inspect(parsed, func(n ast.Node) bool {
			lit, ok := n.(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING || !strings.HasPrefix(lit.Value, "`") {
				return true
			}
			text, err := strconv.Unquote(lit.Value)
			if err != nil {
				return true
			}
			for _, name := range word.FindAllString(text, -1) {
				used[name] = true
			}
			return true
		})
	}
	return used, nil
}
